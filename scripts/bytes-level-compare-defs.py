#!/usr/bin/env python3
"""A compile-x86 certificate's definitions as a module of their own, for
scripts/bytes-level-compare: its imports and its `fn`s, no theorem, and two
names for what the lowering was given, read off the certificate's own
`_lowers` theorem (the cut program where the optimizer ran, the program
where it did not, and the buffer counts).

    scripts/bytes-level-compare-defs.py <certificate.hthr> <out.hthr>
"""
import re
import sys

src = open(sys.argv[1]).read()
keep, item = [], None
for line in src.split('\n'):
    if line and line[0] not in ' \t})]':
        item = 'fn' if line.startswith('fn ') else ('import' if line.startswith('import ') else 'other')
    if item in ('fn', 'import'):
        keep.append(line)
m = re.search(r'theorem (\w+)_lowers\(\): lower_program_roomed\((\w+\(\)), (\w+\(\)), (\[\]|\w+\(\)), (\w+\(\))\)', src)
# A structure returned through memory: the root lowered after the rest
# (`lower_program_sized(root, earlier, …)`), the program being the two.
sized = re.search(r'theorem (\w+)_lowers\(\): lower_program_sized\((\w+\(\)), (\w+\(\)), (\w+\(\)), (\[\]|\w+\(\)), (\w+\(\))\)', src)
if m:
    keep.append('fn %s_lowered() → List<Function> { %s }' % (m.group(1), m.group(2)))
    keep.append('fn %s_lowered_counts() → List<Nat> { %s }' % (m.group(1), m.group(4)))
elif sized:
    keep.append('fn %s_lowered() → List<Function> { Cons(%s, %s) }' % (sized.group(1), sized.group(2), sized.group(3)))
    keep.append('fn %s_lowered_counts() → List<Nat> { %s }' % (sized.group(1), sized.group(5)))
else:
    sys.exit('no `_lowers` theorem in ' + sys.argv[1])
with open(sys.argv[2], 'w') as out:
    out.write('// Generated by scripts/bytes-level-compare from a compile-x86 certificate: its definitions.\n')
    out.write('\n'.join(keep) + '\n')
