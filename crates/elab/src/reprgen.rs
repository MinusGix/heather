//! `reprgen` — the transfer generator (`docs/datarepr-design.md` §3).
//!
//! Certgen's sibling, and untrusted for the same reason: it emits **surface
//! source** — a derived body, its closing lemma, its `refines` theorem and the
//! `impl` that registers them — which the ordinary pipeline then checks. A
//! wrong emission is a failed declaration, never a wrong certificate. Declining
//! with a reason is a supported answer (§3.3).
//!
//! Phases, per §3.1: 0 resolution, 1 eligibility, 2 transcription,
//! 3 obligation synthesis, 4 certificate emission. What §3.1 did not say, and
//! the hand-run found (`crates/elab/tests/reprgen.rs`), is that phase 4 is not
//! only a fold over laws: the spec function does **not** definitionally equal
//! its own recursor unfolding — both are recursive globals — so the generator
//! has to emit an *induction* linking them, and the congruence steps of that
//! induction have to be explicit `j` motives, because the prelude's
//! anti-unifying `cong` cannot generalize two sides that differ inside the
//! recursor's own algebra arguments.
//!
//! There are **two** closing-lemma shapes, chosen by the result type. When the
//! result is the repr'd type the fold's algebra lives at the carrier, so there
//! is no "the spec fn equals its recursor unfolding" to state — the recursor's
//! result is a repr value. The lemma is `abs` pushed through the image spine
//! instead, and it costs a third lemma: every commutation law demands `inv` at
//! its recursive arguments, and the fold's accumulator satisfies `inv` only by
//! an induction of its own (§3.3's second as-landed note).
//!
//! **Callee `Impl`s** (§3.1 phase 0's other half) rest on one structural fact,
//! found by the hand-run before this stage was built: an arm's algebra is
//! *spelled once and typed twice* — at `S` for the anchor law's spec algebra,
//! at the carrier for the fold — so the only expressions an arm may contain
//! are those that are well-typed under both readings. A resolved callee call
//! is spelled `Impl_Rp_g::body(…)` on **both** sides; what bridges it to the
//! spec function `g` is not the anchor law but the *closing induction*, where
//! each callee step is discharged by that callee's own `refines` (and, at a
//! callee returning `S`, its `refines_inv` paying the `inv` hypothesis the
//! next law demands).

use std::cell::RefCell;
use std::collections::HashMap;
use std::rc::Rc;

use heather_syntax::{Decl, Expr, ExprKind};

use crate::datarepr::{
    appc, impl_record_name, lams, params_src, spec_rec_name, spell_ty, CtorView,
};
use crate::Elaborator;

/// One transfer: the surface source, plus what a caller needs to key it.
pub struct ReprEmission {
    /// The spec function transferred.
    pub op: String,
    /// The repr it was transferred to.
    pub repr: String,
    /// The emitted declarations, in dependency order — a recursively generated
    /// callee's artifacts come before the caller's, so elaborating the text
    /// front to back registers each `Impl` before the one that resolves it.
    pub text: String,
    /// Where the target's own `impl` block starts in `text`.
    ///
    /// For the one caller that wants the transfer's **certificate** without its
    /// **registration**: `refines := via_derived(p)` composes with the derived
    /// `refines`, and at one `(repr, operation)` key there is only ever one
    /// `Impl` — the declaration the user is writing (design FINDING E). So that
    /// route elaborates `text[..impl_at]` and states the composition itself.
    pub impl_at: usize,
    /// The derived body, its `refines`, and (at a repr-typed result) its
    /// `refines_inv`: the names the same caller composes with.
    pub body: String,
    pub refines: String,
    pub refines_inv: Option<String>,
    /// The parameter the transfer recursed on — the one the derived `refines`
    /// takes its single `inv` hypothesis at.
    pub rec_param: String,
}

/// What the *target* transfer (as opposed to a recursively generated callee's)
/// emitted, recorded as its `impl` block is written.
struct Target {
    impl_at: usize,
    body: String,
    refines: String,
    refines_inv: Option<String>,
    rec_param: String,
}

impl Target {
    fn at(
        impl_at: usize,
        body: &str,
        refines: &str,
        refines_inv: Option<&str>,
        rec_param: &str,
    ) -> Option<Target> {
        Some(Target {
            impl_at,
            body: body.to_string(),
            refines: refines.to_string(),
            refines_inv: refines_inv.map(|s| s.to_string()),
            rec_param: rec_param.to_string(),
        })
    }
}

/// A callee that touches `S`, resolved against the `Impl` registry (§3.1
/// phase 0). Provenance is deliberately absent: an `Impl` generated by a
/// recursive transfer, written by hand, or certified via-derived is the same
/// four names to the caller's certificate, which is what the registry's
/// openness (§1.2, the cost basis) is *for*.
struct Callee {
    /// The spec function.
    op: String,
    /// Its `Impl` record — the namespace holding `body`, `refines` and
    /// `refines_inv`.
    record: String,
    /// Per parameter, in declaration order: is it at `S`? The `Impl` restates
    /// the signature with `S ↦ R` at exactly these positions, and `refines`
    /// takes an `inv` hypothesis for each of them, after all the arguments.
    at_s: Vec<bool>,
    /// Does it return `S`? Then `refines` concludes through `abs` and a
    /// `refines_inv` exists.
    res_is_s: bool,
}

/// A node of an arm's tree, in a position whose value is at `S`. The repr side
/// reads it with the constructor *images* and the callees' `Impl` bodies; the
/// spec side with the constructors and the spec functions; the closing lemmas
/// walk it in step. The two kinds carry the same four slots — an image, a spec
/// spelling, a commutation law and a closure law — which is why callee
/// resolution gives the *spine* a branch and the proof schema none.
enum Kind {
    /// `S`'s constructor at this index: `Repr_N::mk_C()`, `C_abs`, `C_inv`.
    Ctor(usize),
    /// A resolved callee: `Impl_Rp_g::body()`, `refines`, `refines_inv`.
    Call(Rc<Callee>),
}

/// An arm body (or sub-expression) whose value is at the repr'd type.
enum Spine {
    /// The result of the recursion on this child — the fold's accumulator.
    Acc(String),
    Node(Kind, Vec<SArg>),
}

enum SArg {
    /// A position that is *not* at `S`: spelled once and identical on both
    /// sides.
    NonRec(String),
    /// A position at `S`: recursive for a constructor, repr-typed for a callee.
    Rec(Spine),
}

/// A place in an arm body where the repr side and the spec side differ, and
/// which the certificate's rewrite chain therefore has to index. Only reached
/// where the arm's own value is not at `S`; at a repr-typed result the whole
/// arm is one spine and the spine's own walk does this work.
enum Site {
    /// A self-call: the recursion's result on this child. Closed by the
    /// closing induction's hypothesis.
    SelfCall(String),
    /// A resolved callee call. Closed by that callee's `refines`.
    Callee(Spine),
}

/// One arm of the recursion, as phases 2 and 4 both need it.
struct Arm<'a> {
    ctor: &'a CtorView,
    /// The arm's pattern binders, in field order, as the source wrote them.
    binders: Vec<String>,
    /// The arm's body.
    body: &'a Expr,
}

/// The one shape v1 transfers: `f(q⃗, x: S)` defined by a total `match` on
/// `x`. Everything else declines with a reason (§3.3).
struct Fragment<'a> {
    /// The recursion parameter's name.
    rec_param: String,
    /// Its index in the declaration's parameter list — where a self-call
    /// carries the recursive child, and the one argument of a self-call that
    /// may differ from the corresponding parameter.
    rec_ix: usize,
    /// The other parameters, `(name, spelled type)`, none of them at `S`.
    others: Vec<(String, String)>,
    /// *All* parameters in declaration order, the recursion one spelled at
    /// `S`. Calls to `f` are built from this and not from `others + rec`: the
    /// `S` parameter need not be the last one, and the `Impl` record restates
    /// the signature in declaration order.
    params: Vec<(String, String)>,
    /// The result type, spelled. `S` itself is the repr-typed-result case,
    /// which takes the second closing-lemma shape (§3.3, as-landed).
    result: String,
    arms: Vec<Arm<'a>>,
}

impl Elaborator {
    /// Transfer `op` to repr `repr`, emitting a derived `Impl` (§3).
    ///
    /// Pure: it reads the registries and returns text. Nothing is declared
    /// until a caller elaborates the emission, which is what keeps a declined
    /// or wrong transfer from leaving anything behind — including the
    /// recursively generated callee `Impl`s, which are part of the same text
    /// and land or fail with it.
    pub fn reprgen(&self, op: &str, repr: &str) -> Result<ReprEmission, String> {
        if !self.datarepr_by_name.contains_key(repr) {
            return Err(format!("`{repr}` is not a `datarepr` in scope"));
        }
        if !self.decls.contains_key(op) {
            return Err(format!("`{op}` is not a declared function here"));
        }
        if self.impl_global(repr, op).is_some() {
            return Err(format!(
                "`{op}` already has an `Impl` at `{repr}`: a transfer does not overwrite \
                 a hand override"
            ));
        }
        let mut out = String::new();
        let mut done: Vec<String> = Vec::new();
        let mut stack: Vec<String> = Vec::new();
        // The target's own `impl` block is the LAST one emitted — the recursion
        // emits a callee's artifacts before the caller's — so the last write
        // here is the top-level transfer's.
        let mut target = None;
        self.transfer(op, repr, &mut out, &mut done, &mut stack, &mut target)?;
        let t = target.expect("a successful transfer emits its `impl` block");
        Ok(ReprEmission {
            op: op.to_string(),
            repr: repr.to_string(),
            text: out,
            impl_at: t.impl_at,
            body: t.body,
            refines: t.refines,
            refines_inv: t.refines_inv,
            rec_param: t.rec_param,
        })
    }

    /// One transfer, appended to `out` after everything it depends on.
    ///
    /// `done` is what this run has already emitted (a diamond in the callee
    /// graph must not emit an `Impl` twice) and `stack` is the chain of
    /// in-progress targets, which is how a cycle in the callee graph becomes a
    /// decline rather than a hang. The cycle guard is **defensive only**: a
    /// callee has to be declared before its caller, so the surface language
    /// cannot spell a mutually recursive pair in the first place — the same
    /// reason §3.3's non-structural-recursion decline has no fixture.
    fn transfer(
        &self,
        op: &str,
        repr: &str,
        out: &mut String,
        done: &mut Vec<String>,
        stack: &mut Vec<String>,
        target: &mut Option<Target>,
    ) -> Result<(), String> {
        let rp = self
            .datarepr_by_name
            .get(repr)
            .ok_or_else(|| format!("`{repr}` is not a `datarepr` in scope"))?;
        let f = self
            .decls
            .get(op)
            .ok_or_else(|| format!("`{op}` is not a declared function here"))?;
        if !f.tyvars.is_empty() {
            return Err(format!("`{op}` is polymorphic: v1 transfers monomorphic operations"));
        }
        // -- phase 1: eligibility (which runs first — §3.1's as-landed
        //    interleave: the callee set is only known once the arms are
        //    decomposed) -----------------------------------------------------
        let frag = self.fragment(op, f, &rp.written, &rp.ctors)?;

        // -- phase 0: resolution ------------------------------------------
        //
        // The callee closure of the target, in the order the arms mention it.
        // A callee that touches `S` needs its own `Impl`'s `refines` to close
        // the step; one without an `Impl` is recursively a generation target
        // if it is in the fragment, and the decline reason otherwise. The
        // recursion is what puts the emission in topological order.
        stack.push(op.to_string());
        let mut callees: HashMap<String, Rc<Callee>> = HashMap::new();
        for arm in &frag.arms {
            for name in callee_names(arm.body) {
                if name == op || callees.contains_key(&name) {
                    continue;
                }
                let Some(d) = self.decls.get(&name) else { continue };
                if !touches(d, &rp.written) {
                    continue;
                }
                if self.impl_global(repr, &name).is_none() && !done.contains(&name) {
                    if stack.contains(&name) {
                        stack.pop();
                        return Err(format!(
                            "`{op}` and `{name}` call each other and neither has an `Impl` at \
                             `{repr}`: a mutually recursive callee closure has no topological \
                             order to generate in (docs/datarepr-design.md §3.1 phase 0)"
                        ));
                    }
                    if let Err(why) = self.transfer(&name, repr, out, done, stack, target) {
                        stack.pop();
                        return Err(format!(
                            "`{op}` calls `{name}`, which touches `{}` and has no `Impl` at \
                             `{repr}`, and generating one declines: {why}",
                            rp.written
                        ));
                    }
                }
                let c = self.callee_of(&name, d, &rp.written, repr)?;
                callees.insert(name, Rc::new(c));
            }
        }
        stack.pop();

        // -- phase 2: transcription ---------------------------------------
        //
        // The structural match becomes the anchor fold: one step per
        // constructor, the arm's fields as the step's leading binders and the
        // recursive occurrences at the accumulator slots.
        let s = &rp.written;
        let c = &rp.carrier;
        let rec = &rp.record;
        let sr = spec_rec_name(repr);
        let abs = format!("{rec}::abs()");
        let inv = format!("{rec}::inv()");
        // The result at `S` is the repr-typed case: the fold's algebra lives at
        // the *carrier*, so `B` is the carrier and the closing lemma is `abs`
        // pushed through the image spine rather than the spec fn's recursor
        // unfolding (§3.3, as-landed).
        let res_is_spec = frag.result == *s;
        let b = if res_is_spec { c.clone() } else { frag.result.clone() };
        let b = &b;

        let mut steps: Vec<String> = Vec::new();
        let mut spec_steps_v: Vec<String> = Vec::new();
        // Per arm: the image spine (repr-typed result) or the rewrite sites
        // the certificate's chain indexes (everything else).
        let mut spines: Vec<Option<Spine>> = Vec::new();
        let mut sites_v: Vec<Vec<Site>> = Vec::new();
        for arm in &frag.arms {
            let rd = self.reader(op, &frag, &rp.ctors, &callees, res_is_spec);
            let mut bs: Vec<(String, String)> = Vec::new();
            let mut sbs: Vec<(String, String)> = Vec::new();
            for (i, fld) in arm.ctor.fields.iter().enumerate() {
                bs.push((
                    arm.binders[i].clone(),
                    if fld.rec { c.clone() } else { fld.spell.clone() },
                ));
                sbs.push((arm.binders[i].clone(), fld.spell.clone()));
            }
            // Each recursive field gets an accumulator binder; a self-call on
            // that field reads it. v1 requires the correspondence to be exact,
            // which `fragment` has already checked.
            let recs: Vec<&str> = arm
                .ctor
                .fields
                .iter()
                .enumerate()
                .filter(|(_, f)| f.rec)
                .map(|(i, _)| arm.binders[i].as_str())
                .collect();
            for (k, _) in recs.iter().enumerate() {
                bs.push((format!("b{k}"), b.clone()));
                sbs.push((format!("b{k}"), b.clone()));
            }
            let slot = |child: &str| {
                let k = recs.iter().position(|r| *r == child).expect("checked in `fragment`");
                format!("b{k}")
            };
            let sp_ctx = Spelling {
                ctors: rp.ctors.as_slice(),
                rec,
                abs: &abs,
                acc: &slot,
            };
            let (body, spine, sites) = if res_is_spec {
                // At a repr-typed result the arm's *value* is at `S`, and the
                // two closing lemmas walk it as an image spine: constructor
                // nodes and resolved callees down to the recursion's own
                // results. Anything else is outside the fragment.
                let sp = rd.spine(arm.body).ok_or_else(|| rd.reason(op, &arm.ctor.name, s))?;
                (sp_ctx.repr(&sp), Some(sp), Vec::new())
            } else {
                let mut sites: Vec<Site> = Vec::new();
                let body = rd
                    .spell(arm.body, &mut sites, &|_, site| {
                        Some(match site {
                            Site::SelfCall(child) => slot(child),
                            Site::Callee(sp) => sp_ctx.repr(sp),
                        })
                    })
                    .ok_or_else(|| rd.reason(op, &arm.ctor.name, s))?;
                (body, None, sites)
            };
            steps.push(lams(&bs, &body));
            // The SPEC-side algebra: the same body, with the recursive fields
            // bound at `S` instead of the carrier. It is what `fold_law`
            // quantifies over, and the adaptation (`abs` at the child
            // position) beta-reduces it back to the repr step above — which
            // holds precisely because the fragment forbids an arm from
            // mentioning a recursive child outside a self-call, so the binder
            // whose type differs is never used. A resolved callee is spelled
            // through its `Impl` on this side too, for the same reason: the
            // one spelling has to be well-typed under both readings.
            spec_steps_v.push(lams(&sbs, &body));
            spines.push(spine);
            sites_v.push(sites);
        }
        let spec_steps = &spec_steps_v;

        // -- phase 3: obligation synthesis (§1.2's schema) -----------------
        //
        // The signature restated with `S ↦ R`, in declaration order — the same
        // order the `Impl` record restates it in. Read off the ONE schema the
        // surface `impl` declares its obligations from
        // (docs/obligation-records-design.md §2.1): the derived `Impl`'s
        // statements and a hand-written one's are the same paragraph, and were
        // written twice until this call replaced the second copy.
        let sch = self.impl_schema(op, repr)?;
        let params = sch.binders.clone();
        let derived = format!("{op}_derived");
        let arglist: Vec<String> = sch.args();
        // A call to `f` itself, with `x` at the recursion parameter's position.
        let plain_call = |x: &str| {
            let a: Vec<String> = frag
                .params
                .iter()
                .map(|(n, _)| if *n == frag.rec_param { x.to_string() } else { n.clone() })
                .collect();
            format!("{op}({})", a.join(", "))
        };
        let law_binders = sch.law_binders();

        // -- phase 4: certificate emission --------------------------------
        let mut fargs = vec![b.clone()];
        fargs.extend(steps.iter().cloned());
        fargs.push(frag.rec_param.clone());
        out.push_str(&format!(
            "fn {derived}({}) -> {} {{\n    {}\n}}\n\n",
            params_src(&params),
            sch.result,
            appc(&format!("{rec}::fold()"), &fargs)
        ));

        let mut rec_args = vec![b.clone()];
        rec_args.extend(spec_steps.iter().cloned());
        let spec_rec_at = |x: &str| {
            let mut a = rec_args.clone();
            a.push(x.to_string());
            format!("{sr}({})", a.join(", "))
        };
        // Every closing lemma quantifies over the non-recursion parameters and
        // the spec value it inducts on.
        let mut lem_params: Vec<(String, String)> = frag.others.clone();
        lem_params.push(("x".to_string(), s.clone()));
        let lem_params_src =
            lem_params.iter().map(|(n, t)| format!("{n}: {t}")).collect::<Vec<_>>().join(", ");
        let lem_at = |name: &str, x: &str| {
            let mut a: Vec<String> = frag.others.iter().map(|(n, _)| n.clone()).collect();
            a.push(x.to_string());
            format!("{name}({})", a.join(", "))
        };
        let pat_of = |arm: &Arm<'_>| {
            if arm.binders.is_empty() {
                arm.ctor.name.clone()
            } else {
                format!("{}({})", arm.ctor.name, arm.binders.join(", "))
            }
        };
        // The anchor law at this transfer, which both routes open with.
        let mut fl_args = vec![b.clone()];
        fl_args.extend(spec_steps.iter().cloned());
        fl_args.push(frag.rec_param.clone());
        fl_args.push("h0".to_string());
        let fold_law = appc(&format!("{rec}::fold_law()"), &fl_args);
        let law_binders_src = params_src(&law_binders);
        let refines = format!("{op}_derived_refines");

        let inv_pres = format!("{op}_inv_pres");
        let abs_alg = format!("{op}_abs_alg");
        let acc_repr = |child: &str| spec_rec_at(child);
        let sp_ctx =
            Spelling { ctors: rp.ctors.as_slice(), rec, abs: &abs, acc: &acc_repr };
        let acc_inv = |child: &str| lem_at(&inv_pres, child);
        let acc_abs = |child: &str| lem_at(&abs_alg, child);
        let acc_spec = |child: &str| plain_call(child);

        if !res_is_spec {
            // The lemma §3.1 phase 4 did not name: the spec function agrees
            // with its own recursor unfolding. An induction, one arm at a
            // time, each *site* — a recursive occurrence, or a resolved callee
            // call — rewritten by an explicit `j` motive over the proof that
            // closes it.
            let is_rec = format!("{op}_is_rec");
            let lem_call = |x: &str| lem_at(&is_rec, x);
            let mut arms_src = String::new();
            for (arm, sites) in frag.arms.iter().zip(sites_v.iter()) {
                let rd = self.reader(op, &frag, &rp.ctors, &callees, res_is_spec);
                let proof = arm_proof(
                    &rd,
                    arm,
                    sites,
                    &sp_ctx,
                    &spec_rec_at,
                    &lem_call,
                    &acc_inv,
                    &acc_abs,
                    &acc_spec,
                )
                .ok_or_else(|| rd.reason(op, &arm.ctor.name, s))?;
                arms_src.push_str(&format!("        {} => {proof},\n", pat_of(arm)));
            }
            out.push_str(&format!(
                "theorem {is_rec}({lem_params_src}): {} = {} {{\n    match x {{\n{arms_src}    }}\n}}\n\n",
                spec_rec_at("x"),
                plain_call("x")
            ));

            // `fold_law` opens the anchor, the lemma closes it.
            out.push_str(&format!(
                "theorem {refines}({law_binders_src}):\n    {}\n{{\n    trans({fold_law},\n          {})\n}}\n\n",
                sch.refines_concl(&appc(&derived, &arglist)),
                lem_call(&appc(&abs, &[frag.rec_param.clone()]))
            ));
            *target = Target::at(out.len(), &derived, &refines, None, &frag.rec_param);
            out.push_str(&format!(
                "impl {op} for {repr} {{\n    body := {derived},\n    refines := {refines},\n}}\n"
            ));
            done.push(op.to_string());
            return Ok(());
        }

        // -- the repr-typed result (§3.3, as-landed) ----------------------
        //
        // The fold's algebra is at the carrier, so there is no "the spec fn
        // equals its recursor unfolding" to state: the recursor's result is a
        // *repr* value. The closing lemma is `abs` pushed through the image
        // spine instead, and it needs `inv` at every recursive argument of
        // every commutation law — which the accumulator satisfies only by an
        // induction of its own. Three lemmas, in dependency order.

        // Third lemma: the fold's accumulator satisfies `inv`. At `inv = True`
        // every arm is an image closure law applied to `trivial`s and the lemma
        // says nothing; at a canonical-form `inv` it is what the commutation
        // laws below are paid with — and what pays a resolved callee's own
        // `inv` hypotheses.
        let mut arms_src = String::new();
        for (arm, sp) in frag.arms.iter().zip(spines.iter()) {
            let sp = sp.as_ref().expect("a repr-typed result has a spine");
            arms_src.push_str(&format!(
                "        {} => {},\n",
                pat_of(arm),
                sp_ctx.inv_proof(sp, &acc_inv)
            ));
        }
        out.push_str(&format!(
            "theorem {inv_pres}({lem_params_src}): {} {{\n    match x {{\n{arms_src}    }}\n}}\n\n",
            appc(&inv, &[spec_rec_at("x")])
        ));

        // Second closing-lemma shape: one commutation law per constructor
        // node — or `refines` per callee node — and a `j` chain over the
        // positions at `S`.
        let mut arms_src = String::new();
        for (arm, sp) in frag.arms.iter().zip(spines.iter()) {
            let sp = sp.as_ref().expect("a repr-typed result has a spine");
            arms_src.push_str(&format!(
                "        {} => {},\n",
                pat_of(arm),
                sp_ctx.abs_proof(sp, &acc_inv, &acc_abs, &acc_spec)
            ));
        }
        out.push_str(&format!(
            "theorem {abs_alg}({lem_params_src}): {} = {} {{\n    match x {{\n{arms_src}    }}\n}}\n\n",
            appc(&abs, &[spec_rec_at("x")]),
            plain_call("x")
        ));

        // `refines` at a repr-typed result is `abs(body(x̄)) = f(⟦x̄⟧)`
        // (§1.2). The congruence that carries `abs` over the anchor law is an
        // explicit `j` motive, for §3.1 correction 2's reason.
        let derived_call = appc(&derived, &arglist);
        out.push_str(&format!(
            "theorem {refines}({law_binders_src}):\n    {}\n{{\n    \
             trans(j({fold_law},\n            \u{3bb} y q => {} = {}, refl),\n          {})\n}}\n\n",
            sch.refines_concl(&derived_call),
            appc(&abs, &[derived_call.clone()]),
            appc(&abs, &["y".to_string()]),
            lem_at(&abs_alg, &appc(&abs, &[frag.rec_param.clone()]))
        ));
        // …and the second half of §1.2's conclusion: an implementation that
        // *builds* a repr owes `inv` of what it built. The anchor law carries
        // the third lemma back across it.
        let refines_inv = format!("{op}_derived_inv");
        out.push_str(&format!(
            "theorem {refines_inv}({law_binders_src}):\n    {}\n{{\n    \
             j(sym({fold_law}),\n      \u{3bb} y q => {}, {})\n}}\n\n",
            sch.inv_concl(&derived_call),
            appc(&inv, &["y".to_string()]),
            lem_at(&inv_pres, &appc(&abs, &[frag.rec_param.clone()]))
        ));
        *target = Target::at(out.len(), &derived, &refines, Some(&refines_inv), &frag.rec_param);
        out.push_str(&format!(
            "impl {op} for {repr} {{\n    body := {derived},\n    refines := {refines},\n    \
             refines_inv := {refines_inv},\n}}\n"
        ));
        done.push(op.to_string());
        Ok(())
    }

    /// Resolve one callee against the registry, or decline. The record's name
    /// is derived rather than stored, and is the same whether the `Impl` is
    /// already registered or about to be generated by the recursion above —
    /// which is exactly the indifference the open registry promises.
    fn callee_of(&self, name: &str, d: &Decl, s: &str, repr: &str) -> Result<Callee, String> {
        if !d.tyvars.is_empty() {
            return Err(format!(
                "`{name}` is polymorphic: an `Impl` at a v1 repr is over a monomorphic \
                 operation (docs/datarepr-design.md §5.1)"
            ));
        }
        let mut at_s = Vec::new();
        for p in &d.params {
            let Some(t) = spell_ty(&p.ty) else {
                return Err(format!("`{name}`'s parameter `{}` has an unspellable type", p.name));
            };
            at_s.push(t == s);
        }
        Ok(Callee {
            op: name.to_string(),
            record: impl_record_name(repr, name),
            at_s,
            res_is_s: spell_ty(&d.result).as_deref() == Some(s),
        })
    }

    fn reader<'a>(
        &self,
        op: &'a str,
        frag: &'a Fragment<'a>,
        ctors: &'a [CtorView],
        callees: &'a HashMap<String, Rc<Callee>>,
        acc_ok: bool,
    ) -> Read<'a> {
        Read {
            op,
            params: &frag.params,
            rec_ix: frag.rec_ix,
            ctors,
            callees,
            acc_ok,
            why: RefCell::new(None),
        }
    }

    /// Phase 1 — eligibility. An honest syntactic predicate, not a soundness
    /// boundary (§3.1): everything it lets through is still kernel-checked.
    fn fragment<'a>(
        &self,
        op: &str,
        f: &'a Decl,
        s: &str,
        ctors: &'a [CtorView],
    ) -> Result<Fragment<'a>, String> {
        let Some(result) = spell_ty(&f.result) else {
            return Err(format!("`{op}`'s result type cannot be spelled"));
        };
        let mut rec_param = None;
        let mut others = Vec::new();
        let mut params = Vec::new();
        for (i, p) in f.params.iter().enumerate() {
            let Some(t) = spell_ty(&p.ty) else {
                return Err(format!("`{op}`'s parameter `{}` has an unspellable type", p.name));
            };
            params.push((p.name.clone(), t.clone()));
            if t == s {
                if rec_param.is_some() {
                    return Err(format!(
                        "`{op}` takes two parameters at `{s}`: v1 recurses on one \
                         (docs/datarepr-design.md §3.3, as-landed)"
                    ));
                }
                rec_param = Some((p.name.clone(), i));
            } else {
                others.push((p.name.clone(), t));
            }
        }
        let Some((rec_param, rec_ix)) = rec_param else {
            return Err(format!("`{op}` takes no parameter at `{s}`: nothing to transfer"));
        };
        // The body must be a bare `match` on the recursion parameter.
        if !f.body.stmts.is_empty() {
            return Err(format!("`{op}`'s body is not a bare `match`"));
        }
        let ExprKind::Match { scrut, arms, .. } = &f.body.result.kind else {
            return Err(format!(
                "`{op}`'s body is not a structural `match` on `{rec_param}`: outside the \
                 fragment (docs/datarepr-design.md §3.3)"
            ));
        };
        if !matches!(&scrut.kind, ExprKind::Var(v) if *v == rec_param) {
            return Err(format!("`{op}` does not match on its `{s}` parameter"));
        }
        if arms.len() != ctors.len() {
            return Err(format!(
                "`{op}`'s match has {} arms for {} constructors: the fragment needs a total \
                 match in declaration order",
                arms.len(),
                ctors.len()
            ));
        }
        let mut out = Vec::new();
        for (arm, ctor) in arms.iter().zip(ctors) {
            let (name, binders) = pattern_of(arm)
                .ok_or_else(|| format!("`{op}` has an arm this round cannot read"))?;
            if name != ctor.name {
                return Err(format!(
                    "`{op}`'s arms are not in declaration order: expected `{}`, found `{name}`",
                    ctor.name
                ));
            }
            if binders.len() != ctor.fields.len() {
                return Err(format!(
                    "`{op}`'s `{name}` arm binds {} of {} fields: the fragment binds all of \
                     them",
                    binders.len(),
                    ctor.fields.len()
                ));
            }
            let body = arm_body(arm)
                .ok_or_else(|| format!("`{op}`'s `{name}` arm has a body this round cannot read"))?;
            // Every self-call descends on a recursive child of *this* arm and
            // passes the other parameters through unchanged; anything else is
            // a recursion the fold cannot express.
            let recs: Vec<&str> = ctor
                .fields
                .iter()
                .enumerate()
                .filter(|(_, fl)| fl.rec)
                .map(|(i, _)| binders[i].as_str())
                .collect();
            // A recursive child is at the CARRIER on the repr side and at
            // `S` on the spec side, so it may only be reached through a
            // self-call — the one position the fold's accumulator stands in
            // for it. Using one directly would put a carrier value where the
            // spec body has a spec value; at the naive repr that is harmless
            // and at every other repr it is wrong, so it declines at both.
            // Handing it to a *resolved callee* is the same refusal for the
            // same reason: the arm's algebra is spelled once and typed twice,
            // and there is no reading of a child binder that is well-typed
            // under both (§3.3, as-landed).
            for used in vars_outside_self_calls(body, op, rec_ix) {
                if recs.contains(&used.as_str()) {
                    return Err(format!(
                        "`{op}`'s `{name}` arm uses the recursive child `{used}` \
                         outside a self-call: only the recursion's result crosses to \
                         the repr side (docs/datarepr-design.md §3.3, as-landed)"
                    ));
                }
                if used == rec_param {
                    return Err(format!(
                        "`{op}`'s `{name}` arm mentions the scrutinee `{used}`: the arm becomes \
                         the fold's algebra, where the value being matched is not in scope \
                         (docs/datarepr-design.md §3.3)"
                    ));
                }
            }
            for child in self_call_children(body, op, rec_ix) {
                if !recs.contains(&child.as_str()) {
                    return Err(format!(
                        "`{op}` calls itself on `{child}`, which is not a recursive child of \
                         `{name}`: non-structural recursion is outside the fragment \
                         (docs/datarepr-design.md §3.3)"
                    ));
                }
            }
            out.push(Arm { ctor, binders, body });
        }
        Ok(Fragment { rec_param, rec_ix, others, params, result, arms: out })
    }
}

// -- reading an arm body -----------------------------------------------------

/// The reader for one arm: it walks the surface body, classifies every
/// position, and either spells it or declines with a reason. It declines by
/// returning `None` and recording the *first* reason, so a caller reports what
/// the reader actually objected to rather than a generic "cannot spell".
struct Read<'a> {
    op: &'a str,
    /// `f`'s parameters in declaration order.
    params: &'a [(String, String)],
    /// Which of them recurses — where a self-call carries its child.
    rec_ix: usize,
    ctors: &'a [CtorView],
    /// The callees that touch `S`, resolved. A callee absent from this map does
    /// not touch `S` and is spelled unchanged on both sides.
    callees: &'a HashMap<String, Rc<Callee>>,
    /// May a self-call stand at an `S`-typed position? Only when `f`'s own
    /// result is at `S`, where the fold's accumulator is at the carrier.
    acc_ok: bool,
    why: RefCell<Option<String>>,
}

impl Read<'_> {
    fn no<T>(&self, msg: String) -> Option<T> {
        let mut w = self.why.borrow_mut();
        if w.is_none() {
            *w = Some(msg);
        }
        None
    }

    fn reason(&self, op: &str, ctor: &str, s: &str) -> String {
        self.why.borrow().clone().unwrap_or_else(|| {
            format!(
                "`{op}`'s `{ctor}` arm is not a shape this round can spell: an arm is an \
                 application over its binders, the other parameters, self-calls on a \
                 recursive child, resolved callees, and globals that do not touch `{s}`"
            )
        })
    }

    /// A self-call's recursive child, read at the recursion **parameter's
    /// index** — the fragment admits an `S` parameter anywhere in the
    /// signature, so `last()` would pick up an ordinary parameter and blame a
    /// perfectly good declaration for non-structural recursion
    /// (`issues/reprgen-self-call-args-unchecked.md`).
    ///
    /// Every *other* argument has to be the corresponding parameter, spelled
    /// identically: the fold's accumulator carries one value per recursive
    /// child, and nothing varies the other parameters down the recursion. That
    /// half of the check is defensive — the elaborator's own recursion check
    /// refuses a self-call that varies a non-decreasing parameter before the
    /// generator ever sees the declaration (probed 2026-08-15).
    fn self_child(&self, args: &[Expr]) -> Option<String> {
        if args.len() != self.params.len() {
            return self.no(format!(
                "`{}` calls itself with {} argument(s), not {}",
                self.op,
                args.len(),
                self.params.len()
            ));
        }
        for (i, a) in args.iter().enumerate() {
            if i == self.rec_ix {
                continue;
            }
            if !matches!(&a.kind, ExprKind::Var(v) if *v == self.params[i].0) {
                return self.no(format!(
                    "`{}` calls itself with something other than `{}` at parameter `{}`: the \
                     fold's accumulator carries one value per recursive child and nothing \
                     varies the other parameters down the recursion \
                     (docs/datarepr-design.md §3.3)",
                    self.op, self.params[i].0, self.params[i].0
                ));
            }
        }
        match &args[self.rec_ix].kind {
            ExprKind::Var(v) => Some(v.clone()),
            _ => self.no(format!(
                "`{}` calls itself on something that is not a binder: the fold descends on a \
                 recursive child (docs/datarepr-design.md §3.3)",
                self.op
            )),
        }
    }

    /// An expression whose value is at `S`, read as an image spine.
    fn spine(&self, e: &Expr) -> Option<Spine> {
        match &e.kind {
            // A constructor with no fields is a bare name, not an application.
            ExprKind::Var(v) => match self
                .ctors
                .iter()
                .position(|c| c.name == *v && c.fields.is_empty())
            {
                Some(i) => Some(Spine::Node(Kind::Ctor(i), Vec::new())),
                None => self.no(format!(
                    "`{v}` is not an image spine: at a position at the repr'd type an \
                     expression is a constructor, a resolved callee, or the recursion's own \
                     result (docs/datarepr-design.md §3.3, as-landed)"
                )),
            },
            ExprKind::App { head, args, .. } => {
                let ExprKind::Var(h) = &head.kind else {
                    return self.no(format!(
                        "`{}` applies something that is not a name where a value of the \
                         repr'd type is built",
                        self.op
                    ));
                };
                if h == self.op {
                    if !self.acc_ok {
                        return self.no(format!(
                            "`{}` recurses at a position at the repr'd type, but its own \
                             result is not there: the fold's accumulator stands at the \
                             result type (docs/datarepr-design.md §3.3)",
                            self.op
                        ));
                    }
                    return Some(Spine::Acc(self.self_child(args)?));
                }
                if let Some(i) = self.ctors.iter().position(|c| c.name == *h) {
                    if self.ctors[i].fields.len() != args.len() {
                        return self.no(format!(
                            "`{h}` is applied to {} argument(s), not {}",
                            args.len(),
                            self.ctors[i].fields.len()
                        ));
                    }
                    let mut out = Vec::new();
                    for (fld, a) in self.ctors[i].fields.iter().zip(args) {
                        out.push(if fld.rec {
                            SArg::Rec(self.spine(a)?)
                        } else {
                            // A non-recursive field is ordinary data: spelled
                            // once, identical on both sides.
                            SArg::NonRec(self.data(a)?)
                        });
                    }
                    return Some(Spine::Node(Kind::Ctor(i), out));
                }
                if let Some(c) = self.callees.get(h) {
                    if !c.res_is_s {
                        return self.no(format!(
                            "`{h}` does not return the repr'd type, so it cannot stand where \
                             one is built"
                        ));
                    }
                    return Some(Spine::Node(Kind::Call(c.clone()), self.call_args(c, args)?));
                }
                self.no(format!(
                    "`{h}` is not an image spine: it is neither a constructor nor a callee \
                     with an `Impl`, and an arm at the repr'd type is built from \
                     constructors, resolved callees and the recursion's own results \
                     (docs/datarepr-design.md §3.3, as-landed)"
                ))
            }
            _ => self.no(format!(
                "`{}` has an arm that is not an image spine — a numeral where a constructor \
                 belongs, say: at a position at the repr'd type an expression is a \
                 constructor, a resolved callee, or the recursion's own result, and an \
                 honest syntactic predicate declines rather than desugaring \
                 (docs/datarepr-design.md §3.3, as-landed)",
                self.op
            )),
        }
    }

    /// A resolved callee's arguments, split by whether the parameter is at `S`.
    fn call_args(&self, c: &Callee, args: &[Expr]) -> Option<Vec<SArg>> {
        if c.at_s.len() != args.len() {
            return self.no(format!(
                "`{}` is applied to {} argument(s), not {}",
                c.op,
                args.len(),
                c.at_s.len()
            ));
        }
        let mut out = Vec::new();
        for (at, a) in c.at_s.iter().zip(args) {
            out.push(if *at { SArg::Rec(self.spine(a)?) } else { SArg::NonRec(self.data(a)?) });
        }
        Some(out)
    }

    /// Ordinary data: an expression that is spelled identically on both sides,
    /// so it may contain neither a self-call nor a resolved callee.
    fn data(&self, e: &Expr) -> Option<String> {
        let mut sites = Vec::new();
        self.spell(e, &mut sites, &|_, _| None)
    }

    /// An expression whose value is not at `S`. Every **site** — a self-call
    /// or a resolved callee call — is collected in walk order and spelled by
    /// `pick`, which is what lets the certificate's rewrite chain index them.
    /// Sites do not nest: a callee's arguments are read as spines (at `S`) or
    /// as data (elsewhere), and neither admits one.
    fn spell(
        &self,
        e: &Expr,
        sites: &mut Vec<Site>,
        pick: &dyn Fn(usize, &Site) -> Option<String>,
    ) -> Option<String> {
        Some(match &e.kind {
            ExprKind::Var(v) => v.clone(),
            ExprKind::Num(k) => k.to_string(),
            ExprKind::App { head, args, .. } => {
                if let ExprKind::Var(h) = &head.kind {
                    if h == self.op {
                        let child = self.self_child(args)?;
                        let i = sites.len();
                        sites.push(Site::SelfCall(child));
                        return pick(i, &sites[i]).or_else(|| {
                            self.no(format!(
                                "`{}` recurses inside a position that is spelled identically \
                                 on both sides: the certificate's rewrite chain has no index \
                                 for it (docs/datarepr-design.md §3.3)",
                                self.op
                            ))
                        });
                    }
                    if let Some(c) = self.callees.get(h) {
                        let sp = Spine::Node(Kind::Call(c.clone()), self.call_args(c, args)?);
                        let i = sites.len();
                        sites.push(Site::Callee(sp));
                        return pick(i, &sites[i]).or_else(|| {
                            self.no(format!(
                                "`{}` calls `{}`, which touches the repr'd type, inside a \
                                 position that is spelled identically on both sides: the \
                                 certificate's rewrite chain has no index for it \
                                 (docs/datarepr-design.md §3.3)",
                                self.op, c.op
                            ))
                        });
                    }
                }
                let h = self.spell(head, sites, pick)?;
                let mut a = Vec::new();
                for x in args {
                    a.push(self.spell(x, sites, pick)?);
                }
                if a.is_empty() {
                    format!("{h}()")
                } else {
                    format!("{h}({})", a.join(", "))
                }
            }
            ExprKind::Dot { recv, name, .. } => {
                format!("{}.{name}", self.spell(recv, sites, pick)?)
            }
            _ => {
                return self.no(format!(
                    "`{}` has an arm built from a form this round does not spell",
                    self.op
                ))
            }
        })
    }
}

/// Does this declaration mention the repr'd type anywhere in its signature?
/// A callee that does needs its own `Impl` to close a certificate step.
fn touches(d: &Decl, s: &str) -> bool {
    d.params.iter().any(|p| spell_ty(&p.ty).as_deref() == Some(s))
        || spell_ty(&d.result).as_deref() == Some(s)
}

/// Every global applied anywhere in an expression.
fn callee_names(e: &Expr) -> Vec<String> {
    let mut out = Vec::new();
    walk(e, &mut |x| {
        if let ExprKind::App { head, .. } = &x.kind {
            if let ExprKind::Var(n) = &head.kind {
                out.push(n.clone());
            }
        }
    });
    out
}

/// The recursive children `op` descends on, in walk order. Read at the
/// recursion *parameter's* index and not at the last argument: the fragment
/// admits an `S` parameter anywhere in the signature.
fn self_call_children(e: &Expr, op: &str, rec_ix: usize) -> Vec<String> {
    let mut out = Vec::new();
    walk(e, &mut |x| {
        if let ExprKind::App { head, args, .. } = &x.kind {
            if matches!(&head.kind, ExprKind::Var(n) if n == op) {
                if let Some(a) = args.get(rec_ix) {
                    if let ExprKind::Var(v) = &a.kind {
                        out.push(v.clone());
                    }
                }
            }
        }
    });
    out
}

/// Pre-order walk. Deliberately total over the shapes the fragment admits and
/// silent elsewhere: the spelling pass is what refuses an unreadable body, so
/// a shape missed here can never become a wrong emission, only a decline.
fn walk(e: &Expr, f: &mut impl FnMut(&Expr)) {
    f(e);
    match &e.kind {
        ExprKind::App { head, args, .. } => {
            walk(head, f);
            for a in args {
                walk(a, f);
            }
        }
        ExprKind::TyApp { head, .. } => walk(head, f),
        ExprKind::Dot { recv, .. } => walk(recv, f),
        _ => {}
    }
}

/// Spelling a spine, and the three proofs that walk it. The `acc` closure says
/// what the recursion's result on a child *is* on the repr side: the fold's
/// accumulator inside the derived body, the spec recursor at that child inside
/// the lemmas.
struct Spelling<'a> {
    ctors: &'a [CtorView],
    /// The generated record, whose namespace holds the images and their laws.
    rec: &'a str,
    abs: &'a str,
    acc: &'a dyn Fn(&str) -> String,
}

impl Spelling<'_> {
    /// A node's four slots. A constructor and a resolved callee differ in
    /// nothing else, which is why the proofs below do not branch on the kind.
    fn image(&self, k: &Kind) -> String {
        match k {
            Kind::Ctor(i) => format!("{}::mk_{}()", self.rec, self.ctors[*i].name),
            Kind::Call(c) => format!("{}::body()", c.record),
        }
    }

    fn abs_law(&self, k: &Kind) -> String {
        match k {
            Kind::Ctor(i) => format!("{}::{}_abs()", self.rec, self.ctors[*i].name),
            Kind::Call(c) => format!("{}::refines()", c.record),
        }
    }

    fn inv_law(&self, k: &Kind) -> String {
        match k {
            Kind::Ctor(i) => format!("{}::{}_inv()", self.rec, self.ctors[*i].name),
            Kind::Call(c) => format!("{}::refines_inv()", c.record),
        }
    }

    /// The node's spec side: the constructor, or the spec function itself.
    fn spec_app(&self, k: &Kind, args: &[String]) -> String {
        match k {
            Kind::Ctor(i) => ctor_app(&self.ctors[*i].name, args),
            Kind::Call(c) => format!("{}({})", c.op, args.join(", ")),
        }
    }

    /// The spine at the carrier: images and `Impl` bodies over the accumulator.
    fn repr(&self, sp: &Spine) -> String {
        match sp {
            Spine::Acc(child) => (self.acc)(child),
            Spine::Node(k, args) => {
                let a: Vec<String> = args.iter().map(|x| self.arg(x, &|sp| self.repr(sp))).collect();
                appc(&self.image(k), &a)
            }
        }
    }

    /// The same spine at the spec type: constructors and spec functions over
    /// the spec function's own value at the child.
    fn spec(&self, sp: &Spine, acc_spec: &dyn Fn(&str) -> String) -> String {
        match sp {
            Spine::Acc(child) => acc_spec(child),
            Spine::Node(k, args) => {
                let a: Vec<String> =
                    args.iter().map(|x| self.arg(x, &|sp| self.spec(sp, acc_spec))).collect();
                self.spec_app(k, &a)
            }
        }
    }

    fn arg(&self, a: &SArg, f: &dyn Fn(&Spine) -> String) -> String {
        match a {
            SArg::NonRec(t) => t.clone(),
            SArg::Rec(sp) => f(sp),
        }
    }

    /// `inv` of the spine's repr side: each node's closure law — `C_inv` at an
    /// image, `refines_inv` at a callee — applied to the `inv` proofs of its
    /// repr-typed arguments, bottoming out in the `inv`-preservation lemma at
    /// the accumulator.
    fn inv_proof(&self, sp: &Spine, acc_inv: &dyn Fn(&str) -> String) -> String {
        match sp {
            Spine::Acc(child) => acc_inv(child),
            Spine::Node(k, args) => {
                // One argument list, in the law's own binder order: the image's
                // arguments, then one `inv` proof per repr-typed one.
                let mut a: Vec<String> =
                    args.iter().map(|x| self.arg(x, &|sp| self.repr(sp))).collect();
                for sp in rec_args(args) {
                    a.push(self.inv_proof(sp, acc_inv));
                }
                appc(&self.inv_law(k), &a)
            }
        }
    }

    /// `abs` pushed through the spine: at each node the commutation law — the
    /// image's `C_abs`, or the callee's `refines` — then one `j` step per
    /// position at `S`, rewriting `abs(child)` to the spec function's value
    /// there. Explicit motives, for §3.1 correction 2's reason: the sides
    /// differ inside the recursor's algebra arguments.
    ///
    /// At a **callee whose result is not at `S`** the very same term proves the
    /// step without the outer `abs` — `refines` concludes `body(x̄) = g(⟦x̄⟧)`
    /// there — which is why a callee site in the recursor-unfolding lemma
    /// reuses this walk unchanged.
    fn abs_proof(
        &self,
        sp: &Spine,
        acc_inv: &dyn Fn(&str) -> String,
        acc_abs: &dyn Fn(&str) -> String,
        acc_spec: &dyn Fn(&str) -> String,
    ) -> String {
        let (k, args) = match sp {
            Spine::Acc(child) => return acc_abs(child),
            Spine::Node(k, args) => (k, args),
        };
        let mut a: Vec<String> = args.iter().map(|x| self.arg(x, &|sp| self.repr(sp))).collect();
        let recs = rec_args(args);
        for sp in &recs {
            a.push(self.inv_proof(sp, acc_inv));
        }
        let mut proof = appc(&self.abs_law(k), &a);
        // `side(n, y)`: the spec-side node with the first `n` positions at `S`
        // already rewritten, and position `n` shown as `y` when a motive is
        // being spelled.
        let side = |n: usize, y: Option<&str>| -> String {
            let mut rank = 0;
            let a: Vec<String> = args
                .iter()
                .map(|x| match x {
                    SArg::NonRec(t) => t.clone(),
                    SArg::Rec(sp) => {
                        let r = rank;
                        rank += 1;
                        match (r.cmp(&n), y) {
                            (std::cmp::Ordering::Less, _) => self.spec(sp, acc_spec),
                            (std::cmp::Ordering::Equal, Some(y)) => y.to_string(),
                            _ => appc(self.abs, &[self.repr(sp)]),
                        }
                    }
                })
                .collect();
            self.spec_app(k, &a)
        };
        for (n, sp) in recs.iter().enumerate() {
            proof = format!(
                "trans({proof}, j({}, \u{3bb} y q => {} = {}, refl))",
                self.abs_proof(sp, acc_inv, acc_abs, acc_spec),
                side(n, None),
                side(n, Some("y"))
            );
        }
        proof
    }
}

fn rec_args(args: &[SArg]) -> Vec<&Spine> {
    args.iter()
        .filter_map(|a| if let SArg::Rec(sp) = a { Some(sp) } else { None })
        .collect()
}

/// `C` or `C(a, b)` — a constructor is applied n-ary, unlike a record field.
fn ctor_app(name: &str, args: &[String]) -> String {
    if args.is_empty() {
        name.to_string()
    } else {
        format!("{name}({})", args.join(", "))
    }
}

/// One arm of the closing lemma's induction: rewrite each **site** from its
/// repr-side spelling to its spec-side one, one explicit `j` motive at a time.
/// A self-call is closed by the induction's own hypothesis; a resolved callee
/// call by that callee's `refines`, chained through the `refines`/`refines_inv`
/// of whatever produced its repr-typed arguments.
///
/// `j` and not `cong`: the two sides differ inside the recursor's algebra
/// arguments, where anti-unification cannot find the function
/// (`issues/congruence-by-anti-unification.md` §3, confirmed by the hand-run).
#[allow(clippy::too_many_arguments)]
fn arm_proof(
    rd: &Read<'_>,
    arm: &Arm<'_>,
    sites: &[Site],
    sp_ctx: &Spelling<'_>,
    spec_rec_at: &impl Fn(&str) -> String,
    lem_call: &impl Fn(&str) -> String,
    acc_inv: &dyn Fn(&str) -> String,
    acc_abs: &dyn Fn(&str) -> String,
    acc_spec: &dyn Fn(&str) -> String,
) -> Option<String> {
    if sites.is_empty() {
        return Some("refl".to_string());
    }
    let repr_of = |site: &Site| match site {
        Site::SelfCall(child) => spec_rec_at(child),
        Site::Callee(sp) => sp_ctx.repr(sp),
    };
    let spec_of = |site: &Site| match site {
        Site::SelfCall(child) => acc_spec(child),
        Site::Callee(sp) => sp_ctx.spec(sp, acc_spec),
    };
    // `state(n, y)` spells the arm with the first `n` sites already rewritten
    // to the spec side, and site `y` — when given — shown as the motive's
    // bound variable.
    let state = |n: usize, y: Option<usize>| -> Option<String> {
        let mut v = Vec::new();
        rd.spell(arm.body, &mut v, &|i, site| {
            Some(if Some(i) == y {
                "y".to_string()
            } else if i < n {
                spec_of(site)
            } else {
                repr_of(site)
            })
        })
    };
    let mut steps: Vec<String> = Vec::new();
    for (n, site) in sites.iter().enumerate() {
        let from = state(n, None)?;
        let motive = state(n, Some(n))?;
        let p = match site {
            Site::SelfCall(child) => lem_call(child),
            Site::Callee(sp) => sp_ctx.abs_proof(sp, acc_inv, acc_abs, acc_spec),
        };
        steps.push(format!("j({p}, \u{3bb} y q => {from} = {motive}, refl)"));
    }
    let mut proof = steps.pop().expect("non-empty");
    while let Some(s) = steps.pop() {
        proof = format!("trans({s}, {proof})");
    }
    Some(proof)
}

// -- reading the surface `match` --------------------------------------------

fn pattern_of(arm: &heather_syntax::Arm) -> Option<(String, Vec<String>)> {
    use heather_syntax::Pat;
    // A default arm stands for several constructors and binds nothing; the
    // fragment asks for them written out (§3.3 — an honest syntactic
    // predicate, so it declines rather than expanding).
    if arm.default {
        return None;
    }
    let mut bs = Vec::new();
    for b in &arm.binders {
        match b {
            Pat::Var { name, .. } => bs.push(name.clone()),
            Pat::Ctor { .. } => return None,
        }
    }
    Some((arm.ctor.clone(), bs))
}

fn arm_body(arm: &heather_syntax::Arm) -> Option<&Expr> {
    Some(&arm.body)
}

/// Every variable occurrence that is *not* the recursion argument of a
/// self-call. What the fragment checks its recursive binders against.
fn vars_outside_self_calls(e: &Expr, op: &str, rec_ix: usize) -> Vec<String> {
    let mut out = Vec::new();
    go(e, op, rec_ix, &mut out);
    return out;

    fn go(e: &Expr, op: &str, rec_ix: usize, out: &mut Vec<String>) {
        match &e.kind {
            ExprKind::Var(v) => out.push(v.clone()),
            ExprKind::App { head, args, .. } => {
                if matches!(&head.kind, ExprKind::Var(h) if h == op) {
                    // The recursion argument is the one position a recursive
                    // child legitimately appears in.
                    for (i, a) in args.iter().enumerate() {
                        if i != rec_ix {
                            go(a, op, rec_ix, out);
                        }
                    }
                    return;
                }
                go(head, op, rec_ix, out);
                for a in args {
                    go(a, op, rec_ix, out);
                }
            }
            ExprKind::TyApp { head, .. } => go(head, op, rec_ix, out),
            ExprKind::Dot { recv, .. } => go(recv, op, rec_ix, out),
            _ => {}
        }
    }
}
