//! A program's code as the producer lays it out (docs/native-architecture-review.md
//! R4): parts in order, each a fixed piece, a generated piece, a label, or a
//! near jump named by the label it lands on. Offsets and displacements are
//! computed here from the parts' lengths, and nothing restates the library's
//! sums: the library states where each jump lands over its own layout
//! (x86_64_layout's `JumpsForward` and `JumpsBack`), and the certificate
//! proves each of those by evaluation at the written bytes, so a table that
//! disagrees with the library is refused.
use std::collections::HashMap;

use heather_elab::heather_emit::Module;

use super::read_loop::{literal, SYSCALL};

pub(super) const JZ: &[u8] = &[0x0f, 0x84];
pub(super) const JS: &[u8] = &[0x0f, 0x88];
pub(super) const JNZ: &[u8] = &[0x0f, 0x85];
pub(super) const JMP: &[u8] = &[0xe9];

enum Part {
    /// Fixed bytes, declared once as `{prefix}_{name}_written()`; `syscall`
    /// is the library's `syscall_bytes()`.
    Fixed(String, Vec<u8>),
    /// Generated bytes, spelled by their published term; `key` names them
    /// for a caller that spells them otherwise (`spelled_with`).
    Generated { key: &'static str, term: String, bytes: Vec<u8> },
    Label(&'static str),
    /// A near jump: its name, its opcode (the rel32 follows), its target.
    Jump(&'static str, &'static [u8], &'static str),
}

#[derive(Default)]
pub(super) struct Layout { parts: Vec<Part> }

impl Layout {
    pub(super) fn fixed(mut self, name: impl Into<String>, bytes: Vec<u8>) -> Self {
        self.parts.push(Part::Fixed(name.into(), bytes));
        self
    }
    pub(super) fn syscall(self) -> Self { self.fixed("syscall", SYSCALL.to_vec()) }
    pub(super) fn generated(mut self, key: &'static str, term: String, bytes: Vec<u8>) -> Self {
        self.parts.push(Part::Generated { key, term, bytes });
        self
    }
    pub(super) fn label(mut self, name: &'static str) -> Self {
        self.parts.push(Part::Label(name));
        self
    }
    pub(super) fn jump(mut self, name: &'static str, opcode: &'static [u8], to: &'static str) -> Self {
        self.parts.push(Part::Jump(name, opcode, to));
        self
    }
    pub(super) fn then(mut self, rest: Layout) -> Self {
        self.parts.extend(rest.parts);
        self
    }

    fn len(part: &Part) -> usize {
        match part {
            Part::Fixed(_, bytes) | Part::Generated { bytes, .. } => bytes.len(),
            Part::Label(_) => 0,
            Part::Jump(_, opcode, _) => opcode.len() + 4,
        }
    }
    fn labels(&self) -> HashMap<&'static str, usize> {
        let mut labels = HashMap::new();
        let mut at = 0;
        for part in &self.parts {
            if let Part::Label(name) = part {
                assert!(labels.insert(*name, at).is_none(), "label `{name}` placed twice");
            }
            at += Self::len(part);
        }
        labels
    }
    /// Each jump's displacement: from the jump's end to its label, as rel32.
    fn displacements(&self) -> HashMap<&'static str, u32> {
        let labels = self.labels();
        let mut displacements = HashMap::new();
        let mut at = 0;
        for part in &self.parts {
            at += Self::len(part);
            if let Part::Jump(name, _, to) = part {
                let target = *labels.get(to).unwrap_or_else(|| panic!("jump `{name}` to the unplaced label `{to}`"));
                let distance = i32::try_from(target as i64 - at as i64).expect("the program fits a rel32");
                assert!(displacements.insert(*name, distance as u32).is_none(), "jump `{name}` placed twice");
            }
        }
        displacements
    }
    pub(super) fn displacement(&self, jump: &str) -> u32 {
        *self.displacements().get(jump).unwrap_or_else(|| panic!("no jump `{jump}`"))
    }
    /// A part's bytes, jumps with their displacements.
    fn bytes(part: &Part, displacements: &HashMap<&'static str, u32>) -> Vec<u8> {
        match part {
            Part::Fixed(_, bytes) | Part::Generated { bytes, .. } => bytes.clone(),
            Part::Label(_) => Vec::new(),
            Part::Jump(name, opcode, _) => [*opcode, &displacements[name].to_le_bytes()[..]].concat(),
        }
    }
    pub(super) fn code(&self) -> Vec<u8> {
        let displacements = self.displacements();
        self.parts.iter().flat_map(|part| Self::bytes(part, &displacements)).collect()
    }
    /// Each fixed piece's and jump's literal, once: a name used twice must
    /// name the same bytes.
    pub(super) fn declare(&self, module: &mut Module, prefix: &str) {
        let displacements = self.displacements();
        let mut declared: HashMap<String, Vec<u8>> = HashMap::new();
        for part in &self.parts {
            let name = match part {
                Part::Fixed(name, _) if name != "syscall" => name.clone(),
                Part::Jump(name, _, _) => name.to_string(),
                _ => continue,
            };
            let bytes = Self::bytes(part, &displacements);
            match declared.get(&name) {
                Some(earlier) => assert_eq!(earlier, &bytes, "piece `{name}` written twice with different bytes"),
                None => {
                    module.raw(format!("fn {prefix}_{name}_written() → List<BitVec(8)> {{ {} }}", literal(&bytes)));
                    declared.insert(name, bytes);
                }
            }
        }
    }
    /// The parts as the certificate spells them, in order: fixed pieces and
    /// jumps by their literals, generated ones by their terms or by `terms`'
    /// for their key.
    pub(super) fn spelled_with(&self, prefix: &str, terms: &[(&str, &str)]) -> Vec<String> {
        self.parts.iter().filter_map(|part| match part {
            Part::Fixed(name, _) if name == "syscall" => Some("syscall_bytes()".to_string()),
            Part::Fixed(name, _) => Some(format!("{prefix}_{name}_written()")),
            Part::Jump(name, _, _) => Some(format!("{prefix}_{name}_written()")),
            Part::Generated { key, term, .. } =>
                Some(terms.iter().find(|(k, _)| k == key).map_or_else(|| term.clone(), |(_, t)| t.to_string())),
            Part::Label(_) => None,
        }).collect()
    }

    /// A mutation for the controls: `jump` lands on `to` instead.
    #[cfg(test)]
    pub(super) fn retarget(mut self, jump: &str, to: &'static str) -> Self {
        for part in &mut self.parts {
            if let Part::Jump(name, _, target) = part { if *name == jump { *target = to; } }
        }
        self
    }
    /// Another: the fixed piece `piece` a byte longer.
    #[cfg(test)]
    pub(super) fn pad(mut self, piece: &str) -> Self {
        for part in &mut self.parts {
            if let Part::Fixed(name, bytes) = part { if name == piece { bytes.push(0x90); } }
        }
        self
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // Each jump lands on its label, read back from the bytes: forward, back,
    // and to itself.
    #[test]
    fn jumps_land_on_their_labels() {
        let layout = Layout::default().label("top").fixed("a", vec![1, 2, 3]).jump("ahead", JZ, "end").fixed("b", vec![4])
            .jump("back", JMP, "top").label("self").jump("stay", JS, "self").label("end");
        let code = layout.code();
        let read = |at: usize, size: usize| {
            let rel = i32::from_le_bytes(code[at + size - 4..at + size].try_into().unwrap());
            (at + size) as i64 + i64::from(rel)
        };
        assert_eq!(code.len(), 3 + 6 + 1 + 5 + 6);
        assert_eq!(read(3, 6), code.len() as i64);
        assert_eq!(read(10, 5), 0);
        assert_eq!(read(15, 6), 15);
        assert_eq!(layout.spelled_with("p", &[]), ["p_a_written()", "p_ahead_written()", "p_b_written()", "p_back_written()", "p_stay_written()"]);
    }
}
